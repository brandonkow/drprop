/** Reproduce the licensed, bundled fonts used by the offline Edge PDF renderer. */
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';
const root = new URL('../supabase/functions/_shared/', import.meta.url);
mkdirSync(root, { recursive: true });
const fonts = [
  ['body', 'geist', 'Geist_400Regular'],
  ['display', 'instrument-serif', 'InstrumentSerif_400Regular'],
];
let module = '// Generated by scripts/case-pdf-fonts.mjs. Font licenses are adjacent.\n';
for (const [key, family, file] of fonts) {
  const directory = new URL(`../node_modules/@expo-google-fonts/${family}/`, import.meta.url);
  module += `export const ${key} = '${readFileSync(new URL(`400Regular/${file}.ttf`, directory)).toString('base64')}';\n`;
  copyFileSync(new URL('LICENSE_FONT', directory), new URL(`${family}-LICENSE.txt`, root));
}
writeFileSync(new URL('pdf-fonts.ts', root), module);
